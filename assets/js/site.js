/* Raffaele Perego — site behaviour: theme toggle, stats, research
   highlights and the filterable publication list. Data comes from
   assets/js/publications-data.js (generated by scripts/build_publications.py). */
(function () {
  "use strict";

  const ME = "Raffaele Perego";
  const PAGE = 40;
  const root = document.documentElement;

  /* ---------- theme ---------- */
  try {
    const saved = localStorage.getItem("theme");
    if (saved) root.dataset.theme = saved;
  } catch (e) { /* storage unavailable */ }
  document.querySelector(".theme-toggle").addEventListener("click", () => {
    const dark = root.dataset.theme
      ? root.dataset.theme === "dark"
      : matchMedia("(prefers-color-scheme: dark)").matches;
    root.dataset.theme = dark ? "light" : "dark";
    try { localStorage.setItem("theme", root.dataset.theme); } catch (e) { /* ignore */ }
  });

  document.getElementById("stat-awards").textContent =
    document.querySelectorAll("#awards .timeline > li").length;

  const DATA = window.PUBLICATIONS;
  if (!DATA) return;
  const pubs = DATA.publications;

  /* ---------- stats ---------- */
  document.getElementById("stat-total").textContent = DATA.stats.total;
  document.getElementById("stat-a").textContent = DATA.stats.a_conf;
  document.getElementById("stat-years").textContent = DATA.stats.years_active + "+";
  document.getElementById("pub-updated").textContent = new Date(DATA.generated)
    .toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });

  const esc = (s) => String(s).replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const topicLabel = Object.fromEntries(DATA.topics.map((t) => [t.slug, t.label]));
  const research = new Set(["a_conf", "q1", "conf", "journal", "workshop"]);

  /* ---------- research highlights: two recent strong papers per theme ---------- */
  document.querySelectorAll(".theme-papers").forEach((ul) => {
    const topic = ul.dataset.topic;
    const picks = pubs
      .filter((p) => p.topics.includes(topic) && (p.type === "a_conf" || p.type === "q1"))
      .slice(0, 2);
    ul.innerHTML = picks.map((p) =>
      `<li><span class="v">${esc(p.venue)} '${String(p.year).slice(2)}</span>` +
      `<a href="${esc(p.url)}">${esc(p.title)}</a></li>`).join("");
  });

  /* ---------- publication filters ---------- */
  const state = { type: "all", topic: "all", q: "", shown: PAGE };
  const typeOrder = ["selected", "all", "a_conf", "q1", "conf", "journal", "workshop", "book", "edited", "preprint"];
  const typeCount = (t) =>
    t === "all" ? pubs.length :
    t === "selected" ? pubs.filter((p) => p.selected).length :
    pubs.filter((p) => p.type === t).length;
  const typeName = (t) => t === "all" ? "All" : t === "selected" ? "Selected" : DATA.types[t] || t;

  const typeRow = document.getElementById("type-filters");
  typeOrder.filter((t) => typeCount(t) > 0).forEach((t) => {
    typeRow.insertAdjacentHTML("beforeend",
      `<button class="pill" type="button" data-type="${t}" aria-pressed="${t === state.type}">` +
      `${esc(typeName(t))}<span class="n">${typeCount(t)}</span></button>`);
  });

  const topicRow = document.getElementById("topic-filters");
  const topics = [{ slug: "all", label: "All topics" }, ...DATA.topics];
  topics.forEach((t) => {
    const n = t.slug === "all" ? pubs.length : pubs.filter((p) => p.topics.includes(t.slug)).length;
    if (!n) return;
    topicRow.insertAdjacentHTML("beforeend",
      `<button class="pill" type="button" data-topic="${t.slug}" aria-pressed="${t.slug === state.topic}">` +
      `${t.slug === "all" ? "" : "# "}${esc(t.label)}<span class="n">${n}</span></button>`);
  });

  const norm = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();

  function matches(p) {
    if (state.type === "selected" ? !p.selected : state.type !== "all" && p.type !== state.type) return false;
    if (state.topic !== "all" && !p.topics.includes(state.topic)) return false;
    if (state.q) {
      const hay = norm(`${p.title} ${p.authors.join(" ")} ${p.venue} ${p.venue_full} ${p.year}`);
      return norm(state.q).split(/\s+/).every((w) => hay.includes(w));
    }
    return true;
  }

  function renderPub(p) {
    const authors = p.authors.map((a) => a === ME ? `<b>${esc(a)}</b>` : esc(a)).join(", ");
    const links = [];
    if (p.url) links.push(`<a href="${esc(p.url)}">${p.url.includes("doi.org") ? "DOI" : "Link"} ↗</a>`);
    if (p.arxiv && p.type !== "preprint") {
      const href = p.arxiv.startsWith("http") ? p.arxiv : `https://arxiv.org/abs/${p.arxiv}`;
      links.push(`<a href="${esc(href)}">arXiv ↗</a>`);
    }
    const topicsHtml = p.topics.map((t) =>
      `<button type="button" data-topic="${t}"># ${esc(topicLabel[t] || t)}</button>`).join("");
    return `<article class="pub">
      <span class="badge ${p.type}" title="${esc(DATA.types[p.type] || "")}">${esc(p.venue || DATA.types[p.type])}</span>
      <div>
        <p class="pub-title">${p.url ? `<a href="${esc(p.url)}">${esc(p.title)}</a>` : esc(p.title)}</p>
        ${p.award ? `<span class="award">★ ${esc(p.award)}</span>` : ""}
        <p class="pub-authors">${authors}</p>
        <p class="pub-venue">${esc(p.venue_full)}${p.venue_full ? ", " : ""}${p.year}${links.join("")}</p>
        <div class="pub-topics">${topicsHtml}</div>
      </div>
    </article>`;
  }

  const list = document.getElementById("pub-list");
  const more = document.getElementById("pub-more");
  const count = document.getElementById("pub-count");

  function render() {
    const hits = pubs.filter(matches);
    const shown = hits.slice(0, state.shown);
    let html = "", year = null;
    shown.forEach((p) => {
      if (p.year !== year) { year = p.year; html += `<h3 class="pub-year">${year}</h3>`; }
      html += renderPub(p);
    });
    list.innerHTML = html || `<p class="empty">No publications match these filters.</p>`;
    count.textContent = `${hits.length} publication${hits.length === 1 ? "" : "s"}`;
    more.hidden = hits.length <= state.shown;
    more.textContent = `Show more (${hits.length - shown.length} left)`;
    typeRow.querySelectorAll(".pill").forEach((b) => b.setAttribute("aria-pressed", b.dataset.type === state.type));
    topicRow.querySelectorAll(".pill").forEach((b) => b.setAttribute("aria-pressed", b.dataset.topic === state.topic));
  }

  function setTopic(t) { state.topic = t; state.shown = PAGE; render(); }

  typeRow.addEventListener("click", (e) => {
    const b = e.target.closest("[data-type]"); if (!b) return;
    state.type = b.dataset.type; state.shown = PAGE; render();
  });
  topicRow.addEventListener("click", (e) => {
    const b = e.target.closest("[data-topic]"); if (b) setTopic(b.dataset.topic);
  });
  list.addEventListener("click", (e) => {
    const b = e.target.closest("button[data-topic]"); if (!b) return;
    setTopic(b.dataset.topic);
    document.getElementById("publications").scrollIntoView();
  });
  document.querySelectorAll("[data-filter-topic]").forEach((a) =>
    a.addEventListener("click", () => { state.type = "all"; setTopic(a.dataset.filterTopic); }));
  let timer;
  document.getElementById("pub-search").addEventListener("input", (e) => {
    clearTimeout(timer);
    timer = setTimeout(() => { state.q = e.target.value.trim(); state.shown = PAGE; render(); }, 120);
  });
  more.addEventListener("click", () => { state.shown += PAGE; render(); });

  render();
})();
